-- ttl_mst.eff_stt_dt — 신규 칭호는 "만든 뒤에 생긴 일"만 센다.
--
-- 배경(설계 docs/design/2026-07-30-신규-칭호-후보-모임-깅스타그램.md §7.5):
--   안 그러면 시드 sweep 한 번에 과거 몇 년치가 통째로 판정되어, 고인물이 한 번에 대여섯 개를
--   받고 푸시가 그만큼 나간다.
--
-- ⚠️ `crt_at`을 대신 쓰면 안 된다. 컬럼은 이미 있지만 그걸 기준으로 삼으면 **기존 64종이
--   전부 깨진다** — `화석`(가입 3년)·`SUB3`(풀코스 PB)·`고인물`은 소급이 정상 동작이다.
--   nullable 새 컬럼이면 기존 행은 null로 남아 **마이그레이션만으로 아무것도 안 바뀐다.**
--   부수적으로, 시드를 미리 넣어 두고 출시일에 맞춰 여는 것도 가능해진다.
--
-- `date`인 이유는 시각까지 따질 일이 없어서다 — timestamptz면 KST 함정이 하나 더 는다.
--
-- 판정 규칙(§7.5): 기준은 언제나 **그 활동이 실제로 일어난 날**이다.
--   대회 `race_dt` · 모임 `stt_at`(KST 변환) · 깅스타그램 `act_dt` · 마일리지런 활동일.
--   `crt_at`은 실행일이 따로 없을 때(댓글·응원)만 쓴다 — 적재일로 걸면 옛날 기록을 오늘
--   입력하는 것만으로 칭호가 나온다.

ALTER TABLE public.ttl_mst
  ADD COLUMN eff_stt_dt DATE;

COMMENT ON COLUMN public.ttl_mst.eff_stt_dt IS
  '적용 시작일(KST). 이 날짜부터 발생한 활동만 센다. null = 기간 제한 없음(소급) — 기존 64종은 null로 둔다(설계 §7.5).';
